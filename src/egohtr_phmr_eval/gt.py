from __future__ import annotations

import numpy as np
import os
import torch


BODY25_NAMES = (
    "OP Nose", "OP Neck", "OP RShoulder", "OP RElbow", "OP RWrist",
    "OP LShoulder", "OP LElbow", "OP LWrist", "OP MidHip", "OP RHip",
    "OP RKnee", "OP RAnkle", "OP LHip", "OP LKnee", "OP LAnkle",
    "OP REye", "OP LEye", "OP REar", "OP LEar", "OP LBigToe",
    "OP LSmallToe", "OP LHeel", "OP RBigToe", "OP RSmallToe", "OP RHeel",
)


def generate_gt(sample_path, smplx_model_folder, prompt_hmr_repo, gender, device="cuda"):
    import sys
    from pathlib import Path

    repo = str(Path(prompt_hmr_repo).expanduser().resolve())
    if repo not in sys.path:
        sys.path.insert(0, repo)
    from prompt_hmr.smpl_family import SMPLX
    from prompt_hmr.smpl_family.vertex_ids import smplx_to_openpose

    gender = str(gender).lower()
    if gender not in {"male", "female", "neutral"}:
        raise ValueError(f"Unsupported sequence SMPL-X gender: {gender!r}")
    joint_indices = np.asarray(smplx_to_openpose, dtype=np.int64)
    if joint_indices.shape != (25,):
        raise ValueError(f"PromptHMR BODY_25 mapping must have 25 entries, got {joint_indices.shape}")

    with np.load(sample_path, allow_pickle=False) as d:
        body_pose = np.asarray(d["smplx_exomc_body_pose"], dtype=np.float32)
        global_orient = np.asarray(d["smplx_exomc_global_orient"], dtype=np.float32)
        betas = np.asarray(d["smplx_exomc_betas"], dtype=np.float32)
        transl = np.asarray(d["smplx_exomc_transl"], dtype=np.float32)
        stored_joints = np.asarray(d["smplx_exomc_joints"], dtype=np.float32)
        stored_faces = np.asarray(d["smplx_exomc_faces"], dtype=np.int32)

    if stored_joints.ndim != 2 or stored_joints.shape[1] != 3:
        raise ValueError(f"Expected EgoHTR SMPL-X joints shaped (J,3), got {stored_joints.shape}")
    if stored_joints.shape[0] <= int(joint_indices.max()):
        raise ValueError(
            f"EgoHTR has {stored_joints.shape[0]} joints; BODY_25 mapping requires index {joint_indices.max()}"
        )
    # Metric GT comes directly from EgoHTR's supplied joints. Do not substitute
    # joints regenerated by PromptHMR's wrapper, which applies its own corrections.
    gt_joints = stored_joints[joint_indices].copy()

    previous_cwd = Path.cwd()
    os.chdir(repo)
    try:
        # EgoHTR config.yaml provides this sequence's SMPL-X gender. The wrapper's
        # body_joints are deliberately ignored; only its mesh vertices are used.
        model = SMPLX(str(smplx_model_folder), gender=gender).to(device).eval()
        kwargs = {
            "global_orient": torch.from_numpy(global_orient[None]).to(device),
            "body_pose": torch.from_numpy(body_pose[None]).to(device),
            "betas": torch.from_numpy(betas[None]).to(device),
            "transl": torch.from_numpy(transl[None]).to(device),
            "pose2rot": False,
        }
        with torch.no_grad():
            out = model(**kwargs)
    finally:
        os.chdir(previous_cwd)
    vertices = out.vertices[0].detach().cpu().numpy()
    model_joints = out.joints[0].detach().cpu().numpy()
    joint_reconstruction_max_abs = None
    if model_joints.shape == stored_joints.shape:
        joint_reconstruction_max_abs = float(np.max(np.abs(stored_joints - model_joints)))
        if joint_reconstruction_max_abs > 2e-4:
            print(
                "Warning: the configured SMPL-X model does not reproduce EgoHTR joints "
                f"(max abs {joint_reconstruction_max_abs:.6g} m)"
            )
    model_faces = np.asarray(model.faces, dtype=np.int32)
    if stored_faces.shape != model_faces.shape or not np.array_equal(stored_faces, model_faces):
        raise ValueError("EgoHTR and selected SMPL-X model face topology differ; refusing to pair mesh vertices and faces")
    return gt_joints, vertices, stored_faces, joint_indices, joint_reconstruction_max_abs
